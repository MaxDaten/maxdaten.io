// Writes the profile OG card's portrait as a data-URI module (src/lib/server/og-portrait.ts).
// Embedding it avoids any runtime file access: the dev server, `vite preview` and the Vercel
// function bundle all resolve image assets differently. Re-run after changing the portrait.
import sharp from 'sharp';
import { writeFileSync } from 'node:fs';

const SOURCE = 'src/lib/assets/images/authors/jloos-v2.jpeg';
const SIZE = 400; // the card shows it at 370x360 in a fixed 1200x630 image

const jpeg = await sharp(SOURCE)
    .resize(SIZE, SIZE, { fit: 'cover' })
    .jpeg({ quality: 85 })
    .toBuffer();
writeFileSync(
    'src/lib/server/og-portrait.ts',
    `// Generated by scripts/generate-og-portrait.mjs from ${SOURCE}. Do not edit.\n` +
        `export const ogPortraitDataUri =\n    'data:image/jpeg;base64,${jpeg.toString('base64')}';\n`
);
console.log(`og-portrait.ts: ${jpeg.length} bytes JPEG`);
